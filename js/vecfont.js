const ADVANCE = 6; // grid units per character (4 wide + 2 gap)

export function textWidth(text, size) {
  const unit = size / 6;
  return Math.max(0, text.length * ADVANCE - 2) * unit;
}

// Draws `text` with its top edge at y. align: 'left' | 'center' | 'right'.
export function drawText(ctx, text, x, y, size, align = 'left') {
  const unit = size / 6;
  text = String(text).toUpperCase();
  const width = textWidth(text, size);
  let cx = x;
  if (align === 'center') cx = x - width / 2;
  else if (align === 'right') cx = x - width;

  ctx.beginPath();
  for (const ch of text) {
    const strokes = GLYPHS[ch] || GLYPHS['-'];
    for (const stroke of strokes) {
      for (let i = 0; i < stroke.length; i++) {
        const px = cx + stroke[i][0] * unit;
        const py = y + stroke[i][1] * unit;
        if (i === 0) ctx.moveTo(px, py); else ctx.lineTo(px, py);
      }
    }
    cx += ADVANCE * unit;
  }
  ctx.stroke();
}
